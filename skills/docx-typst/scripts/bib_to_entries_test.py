"""Contract tests for bib_to_entries.py: bib auditing, citeproc-output parsing, emit, shorts, CLI.

pandoc and typst are never invoked: render/build/parse_existing are stubbed where main reaches them.
"""

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent))

import bib_to_entries as b

BIB = """\
@article{bebchuk2019,
  author = {Lucian Bebchuk and Alma Cohen},
  title = {T},
}
@article{bad2020,
  author = {A. Bebchuk, A. Cohen & S. Hirst},
}
@book{inst2021,
  author = {{Gibson, Dunn & Crutcher LLP}},
}
@Comment{ignored,
}
@article{ex_14366,
  title = {X},
}
@article{ex143_66,
  title = {Y},
}
"""


@pytest.fixture
def bib(tmp_path):
    p = tmp_path / "s.bib"
    p.write_text(BIB)
    return p


def test_bib_entries_in_file_order_uppercased_and_skips_comment(bib):
    assert b.bib_entries(bib) == {
        "bebchuk2019": "ARTICLE", "bad2020": "ARTICLE", "inst2021": "BOOK",
        "ex_14366": "ARTICLE", "ex143_66": "ARTICLE",
    }


def test_field_value_is_brace_balanced():
    assert b._field_value("author = {{A & B}, C}", "author") == "{A & B}, C"
    assert b._field_value("title = {x}", "author") is None
    assert b._field_value("author = {unclosed", "author") is None


def test_bad_separators_only_at_depth_zero():
    assert b._bad_separators("A, B & C") == "&"
    assert b._bad_separators("A; B") == ";"
    assert b._bad_separators("{Gibson, Dunn & Crutcher LLP}") is None
    assert b._bad_separators("A and B") is None


def test_audit_reports_separator_punctuation_duplicates_and_shared_short(bib):
    entries = {"a": {"short": "Kahan & Rock"}, "b": {"short": "Kahan & Rock"}, "c": {"short": None}}
    problems = b.audit(bib, entries)
    assert ("bad2020: author separates names with '&', which BibTeX reads as one name -- use ' and '"
            in problems)
    assert "keys differ only in punctuation: ex143_66, ex_14366" in problems
    assert ("short form 'Kahan & Rock' is shared by 2 works (a, b) -- needs a title to disambiguate"
            in problems)
    assert not any("inst2021" in p or "bebchuk2019" in p for p in problems)
    assert len(problems) == 3


def test_split_at_sentinel_comma_and_space_separators():
    s = b.PIN_SENTINEL
    assert b.split_at_sentinel(f"123 F.3d 456, {s} (2d Cir. 2019)", "k") == ("123 F.3d 456", ", ", " (2d Cir. 2019)")
    assert b.split_at_sentinel(f"Book {s} (2019)", "k") == ("Book", " ", " (2019)")


def test_split_at_sentinel_errors():
    with pytest.raises(ValueError, match="k: citeproc dropped the sentinel locator"):
        b.split_at_sentinel("no sentinel", "k")
    with pytest.raises(ValueError, match="k: unrecognized pincite separator"):
        b.split_at_sentinel(f"abc;{b.PIN_SENTINEL}", "k")


def test_short_of_extracts_author_before_supra():
    assert b.short_of("Kahan & Rock, #emph[supra] note 8") == "Kahan & Rock"
    assert b.short_of("Kahan, #emph[supra] note 12, at 3") == "Kahan"
    assert b.short_of("Full cite with no supra") is None
    assert b.short_of(None) is None


def test_typ_str_escapes_and_curls_apostrophes_and_drops_terminator():
    assert b.typ_str('say "hi" \\ Investors\' Attention') == '"say \\"hi\\" \\\\ Investors’ Attention"'
    assert b.typ_str("Comm'n") == '"Comm\'n"'
    assert b.typ_str("#emph[T]; (2025)") == '"#emph[T] (2025)"'


def entry(**kw):
    base = {"full": "F", "date": " (2019)", "pin-sep": ", ", "short": "S"}
    return base | kw


def test_emit_sorted_with_none_short_and_hand_authored_marker():
    out = b.emit({"zeta": entry(short=None), "alpha": entry()}, "s.bib", {"alpha"})
    assert out.startswith("// GENERATED by bib_to_entries.py from s.bib -- do not hand-edit.")
    assert out.index('"alpha"') < out.index('"zeta"')
    assert '    short: "S",  // hand-authored\n' in out
    assert "    short: none,\n" in out
    assert '    pin-sep: ", ",\n' in out and out.rstrip().endswith(")")


def test_load_shorts_table_and_flat_forms(tmp_path):
    p = tmp_path / "shorts.toml"
    p.write_text('[shorts]\nk1 = "A, #emph[T]"\n')
    assert b.load_shorts(p, {"k1": {}}) == {"k1": "A, #emph[T]"}
    p.write_text('k1 = "A"\n')
    assert b.load_shorts(p, {"k1": {}}) == {"k1": "A"}


def test_load_shorts_unknown_key_is_fatal(tmp_path):
    p = tmp_path / "shorts.toml"
    p.write_text('[shorts]\nghost = "X"\nk1 = "Y"\n')
    with pytest.raises(SystemExit, match="overrides for keys not in the .bib: ghost"):
        b.load_shorts(p, {"k1": {}})


def test_load_shorts_non_string_and_bad_toml(tmp_path):
    p = tmp_path / "shorts.toml"
    p.write_text("[shorts]\nk1 = 3\n")
    with pytest.raises(SystemExit, match="not strings: k1"):
        b.load_shorts(p, {"k1": {}})
    p.write_text("[shorts\n")
    with pytest.raises(SystemExit, match=r"shorts\.toml: "):
        b.load_shorts(p, {})


def test_diff_reports_new_dropped_changed_and_exits_1(monkeypatch, tmp_path, capsys):
    monkeypatch.setattr(b, "parse_existing", lambda p: {
        "same": entry(), "gone": entry(), "chg": entry(full="OLD")})
    rc = b.diff({"same": entry(), "new": entry(), "chg": entry(full="NEW")}, tmp_path / "cite-data.typ")
    out = capsys.readouterr().out
    assert rc == 1
    assert "3 entries; generated 3" in out
    assert "  + new" in out and "  - gone" in out
    assert "[chg] full\n    have: 'OLD'\n    want: 'NEW'" in out
    assert "Nothing was written." in out


def test_diff_no_deltas_exits_0(monkeypatch, tmp_path, capsys):
    monkeypatch.setattr(b, "parse_existing", lambda p: {"k": entry(short=None)})
    assert b.diff({"k": entry(short=None)}, tmp_path / "c.typ") == 0
    assert "no deltas." in capsys.readouterr().out


def test_parse_existing_without_typst_exits(monkeypatch, tmp_path):
    monkeypatch.setattr(b.shutil, "which", lambda n: None)
    with pytest.raises(SystemExit, match="typst not found on PATH"):
        b.parse_existing(tmp_path / "c.typ")


def run_main(monkeypatch, argv):
    monkeypatch.setattr(sys, "argv", ["bib_to_entries.py", *argv])
    return b.main()


def test_main_missing_bib_exits_with_message(monkeypatch, tmp_path):
    with pytest.raises(SystemExit, match="error: no such file: "):
        run_main(monkeypatch, ["--bib", str(tmp_path / "x.bib"), "--csl", str(tmp_path / "x.csl")])


def test_main_empty_render_is_fatal(monkeypatch, bib, tmp_path):
    csl = tmp_path / "s.csl"
    csl.write_text("")
    monkeypatch.setattr(b, "build", lambda *a: {})
    with pytest.raises(SystemExit, match="error: citeproc rendered nothing"):
        run_main(monkeypatch, ["--bib", str(bib), "--csl", str(csl)])


def test_main_audit_exit_code_follows_problems(monkeypatch, bib, tmp_path, capsys):
    csl = tmp_path / "s.csl"
    csl.write_text("")
    monkeypatch.setattr(b, "build", lambda *a: {"bebchuk2019": entry()})
    assert run_main(monkeypatch, ["--bib", str(bib), "--csl", str(csl), "--audit"]) == 1
    cap = capsys.readouterr()
    assert "s.bib: 1 entries, 2 problems" in cap.out
    assert "warning: bad2020: author separates" in cap.err


def test_main_writes_module_and_applies_shorts(monkeypatch, tmp_path, capsys):
    bib = tmp_path / "ok.bib"
    bib.write_text("@article{k1,\n  author = {A and B},\n}\n")
    csl = tmp_path / "s.csl"
    csl.write_text("")
    shorts = tmp_path / "shorts.toml"
    shorts.write_text('[shorts]\nk1 = "Mine"\n')
    out = tmp_path / "cite-data.typ"
    monkeypatch.setattr(b, "build", lambda *a: {"k1": entry(short="Theirs")})
    rc = run_main(monkeypatch, ["--bib", str(bib), "--csl", str(csl), "--shorts", str(shorts), "-o", str(out)])
    assert rc == 0
    text = out.read_text()
    assert 'short: "Mine",  // hand-authored' in text and "Theirs" not in text
    cap = capsys.readouterr()
    assert f"wrote {out} (1 entries)" in cap.out
    assert "shorts.toml: 1 hand-authored short forms" in cap.err


def test_build_refuses_bib_containing_sentinel(tmp_path):
    bib = tmp_path / "s.bib"
    bib.write_text("@article{k,\n  note = {9990001},\n}\n")
    with pytest.raises(SystemExit, match="9990001 occurs in s.bib; pick another sentinel"):
        b.build(bib, tmp_path / "x.csl", None)


def test_build_skips_unresolved_and_missing_keys(monkeypatch, bib, tmp_path, capsys):
    s = b.PIN_SENTINEL
    monkeypatch.setattr(b, "render", lambda bib_, csl, keys: {
        "bebchuk2019": {"PIN": f"Lucian Bebchuk, T, {s} (2019).", "SHORT": "Bebchuk, #emph[supra] note 3"},
        "bad2020": {"PIN": "#strong[bad2020?];", "SHORT": "x"},
    })
    got = b.build(bib, tmp_path / "x.csl", ["bebchuk2019", "bad2020", "ex_14366", "nope"])
    assert got == {"bebchuk2019": {"full": "Lucian Bebchuk, T", "date": " (2019)",
                                   "pin-sep": ", ", "short": "Bebchuk"}}
    err = capsys.readouterr().err
    assert "warning: key not in s.bib: nope" in err
    assert "warning: bad2020 unresolved by citeproc; skipped" in err
    assert "warning: no rendering for ex_14366" in err


def test_render_unescapes_underscore_keys(monkeypatch, tmp_path):
    class P:
        returncode = 0
        stderr = "[WARNING] Citeproc: citation zz not found\n"
        stdout = ("PIN::ex\\_1::#footnote[Full, 9990001 (2025).]\n"
                  "SHORT::ex\\_1::#footnote[Auth, #emph[supra] note 1.]\nother line\n")
    monkeypatch.setattr(b, "require_pandoc", lambda: "pandoc")
    monkeypatch.setattr(b.subprocess, "run", lambda *a, **k: P())
    got = b.render(tmp_path / "b.bib", tmp_path / "c.csl", ["ex_1"])
    assert got == {"ex_1": {"PIN": "Full, 9990001 (2025).", "SHORT": "Auth, #emph[supra] note 1."}}
